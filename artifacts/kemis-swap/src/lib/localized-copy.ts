export function relativeTime(date:string,lang:string) {
  const seconds=Math.round((new Date(date).getTime()-Date.now())/1000);
  const [amount,unit]:[number,Intl.RelativeTimeFormatUnit]=Math.abs(seconds)<60?[seconds,"second"]:
    Math.abs(seconds)<3600?[Math.round(seconds/60),"minute"]:Math.abs(seconds)<86400?[Math.round(seconds/3600),"hour"]:[Math.round(seconds/86400),"day"];
  return new Intl.RelativeTimeFormat(lang==="am"?"am-ET":"en",{numeric:"auto"}).format(amount,unit);
}
